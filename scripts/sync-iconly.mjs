import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
const root = fileURLToPath(new URL('../', import.meta.url)),
  hash = b => crypto.createHash('sha256').update(b).digest('hex');
const index = process.argv.indexOf('--source'),
  target = path.join(root, 'src/dziri/iconly.generated.ts'),
  receipt = path.join(root, 'docs/iconly-contract.json');
if (index >= 0) {
  const source = path.resolve(process.argv[index + 1], 'apps/dziri/public/icons/iconly'),
    catalog = JSON.parse(fs.readFileSync(source + '/catalog.json'));
  fs.mkdirSync(path.join(root, 'assets/iconly'), { recursive: true });
  for (const entry of Object.values(catalog.entries)) {
    if (!/^[a-z0-9-]+\.(svg|png)$/.test(entry.file)) throw Error('Invalid Iconly asset path');
    const bytes = fs.readFileSync(source + '/' + entry.file);
    if (hash(bytes) !== entry.sha256) throw Error('Canonical Iconly asset changed');
    fs.writeFileSync(path.join(root, 'assets/iconly', entry.file), bytes);
  }
  const text =
    '// Original Iconly V3 Regular assets; generated by scripts/sync-iconly.mjs.\nexport const iconlySources = {\n' +
    Object.entries(catalog.entries)
      .map(([key, e]) => `  ${key}: require('../../assets/iconly/${e.file}'),`)
      .join('\n') +
    '\n} as const;\nexport type IconlyName = keyof typeof iconlySources;\n';
  fs.writeFileSync(target, text);
  execFileSync(
    process.execPath,
    [path.join(root, 'node_modules/prettier/bin/prettier.cjs'), '--write', target],
    { stdio: 'pipe' },
  );
  fs.writeFileSync(
    receipt,
    JSON.stringify(
      {
        version: 1,
        sourceFile: catalog.sourceFile,
        archiveSha256: catalog.archiveSha256,
        generatedSha256: hash(fs.readFileSync(target)),
        entries: catalog.entries,
      },
      null,
      2,
    ) + '\n',
  );
}
const proof = JSON.parse(fs.readFileSync(receipt));
if (hash(fs.readFileSync(target)) !== proof.generatedSha256) throw Error('Iconly registry drift');
for (const e of Object.values(proof.entries))
  if (hash(fs.readFileSync(path.join(root, 'assets/iconly', e.file))) !== e.sha256)
    throw Error('Iconly asset drift');
console.log('Original Iconly assets verified: ' + Object.keys(proof.entries).length);
